import { NextResponse, type NextRequest } from 'next/server';
import { z } from 'zod';
import { parseJson } from '@/lib/smartUtility/http';
import { requireCemeteryApi } from '@/lib/cemetery/http';
import { cemeteryDbError } from '@/lib/cemetery/errors';

const schema = z.object({
  name: z.string().trim().min(1).max(200),
  addressLine1: z.string().trim().max(200).optional().nullable(),
  city: z.string().trim().max(120).optional().nullable(),
  province: z.string().trim().max(120).optional().nullable(),
  tenureModel: z.enum(['burial_rights', 'land_sale']),
  rightsTermYears: z.number().int().min(1).max(999).optional().nullable(),
  notes: z.string().trim().max(2000).optional().nullable(),
  sections: z
    .array(
      z.object({
        code: z
          .string()
          .trim()
          .toUpperCase()
          .regex(/^[A-Z0-9]{1,6}$/, 'Use 1–6 letters or digits'),
        name: z.string().trim().min(1).max(120),
        siteCount: z.number().int().min(1).max(2000),
        sitesPerRow: z.number().int().min(1).max(50),
        listPrice: z.number().min(0).max(10_000_000).optional().nullable(),
        lengthM: z.number().positive().max(100).optional().nullable(),
        widthM: z.number().positive().max(100).optional().nullable(),
      }),
    )
    .min(1)
    .max(26)
    .refine((s) => new Set(s.map((x) => x.code)).size === s.length, 'Section codes must be unique'),
});

/**
 * POST /api/v1/cemetery/cemeteries — create a cemetery with its sections and grave sites (manager+). Sites are
 * generated by cemetery_generate_sites(), which is idempotent per section, so a retried request after a partial
 * failure completes the structure instead of duplicating it.
 */
export async function POST(request: NextRequest) {
  const auth = await requireCemeteryApi('manage');
  if ('response' in auth) return auth.response;
  const parsed = await parseJson(request, schema);
  if ('response' in parsed) return parsed.response;
  const d = parsed.data;
  const { supabase, ctx, user } = auth;

  const { data: cemetery, error } = await supabase
    .from('cemeteries')
    .insert({
      org_id: ctx.orgId,
      name: d.name,
      address_line1: d.addressLine1 || null,
      city: d.city || null,
      province: d.province || null,
      tenure_model: d.tenureModel,
      rights_term_years: d.rightsTermYears ?? null,
      notes: d.notes || null,
      created_by: user.id,
    })
    .select('id')
    .single();
  if (error) {
    if (error.code === '23505') {
      return NextResponse.json(
        { error: { code: 'duplicate_name', message: 'A cemetery with this name already exists.' } },
        { status: 409 },
      );
    }
    return cemeteryDbError(error, 'Could not create the cemetery.', 'cemeteries.create');
  }

  let sitesCreated = 0;
  for (const [i, s] of d.sections.entries()) {
    const { data: section, error: sErr } = await supabase
      .from('cemetery_sections')
      .insert({
        org_id: ctx.orgId,
        cemetery_id: cemetery.id,
        code: s.code,
        name: s.name,
        sort_order: i,
        sites_per_row: s.sitesPerRow,
      })
      .select('id')
      .single();
    if (sErr) return cemeteryDbError(sErr, 'Could not create a section.', 'cemeteries.section');
    const { data: created, error: gErr } = await supabase.rpc('cemetery_generate_sites', {
      p_section_id: section.id,
      p_count: s.siteCount,
      p_list_price: s.listPrice ?? null,
      p_length_m: s.lengthM ?? null,
      p_width_m: s.widthM ?? null,
    });
    if (gErr)
      return cemeteryDbError(gErr, 'Could not create the grave sites.', 'cemeteries.generate');
    sitesCreated += Number(created ?? 0);
  }

  return NextResponse.json({ cemetery: { id: cemetery.id }, sitesCreated }, { status: 201 });
}
