// Customer-facing compatible-meter catalogue (docs/SA_SMART_METER_CATALOGUE.md is the evidence
// behind every entry). Client-safe: no server imports. Prices are a dated snapshot from SA retailer
// pages; `null` means not published/verified — never a guess.
//
// Status vocabulary (the brief's four classes):
//   verified_ready          — proven end-to-end in Proplyst without hardware ambiguity
//   needs_hardware_testing  — implemented against published documentation; not yet run on a real device
//   supplier_approval       — needs a vendor agreement, keys or partner API access
//   unsupported             — no documented integration path

import type { ProviderId } from './providers';

export type CatalogueStatus = 'verified_ready' | 'needs_hardware_testing' | 'supplier_approval' | 'unsupported';
export type CatalogueConnection = 'manual' | 'lorawan' | 'wifi' | 'modbus_gateway' | 'nbiot' | 'cloud' | 'any_http';

export interface CataloguePrice {
  amountZar: number;
  vat: 'incl' | 'excl' | 'unknown';
  supplier: string;
  url: string;
  seenOn: string;
}

export interface CatalogueEntry {
  id: string;
  manufacturer: string;
  model: string;
  utilityType: 'water' | 'electricity';
  description: string;
  roles: ('main' | 'check' | 'submeter')[];
  connection: CatalogueConnection;
  /** Integration paths Proplyst can use for this hardware (first = recommended). */
  providers: ProviderId[];
  /** Meter connectivity value stored on utility_meters. */
  meterConnectivity: 'manual' | 'lorawan' | 'wifi' | 'modbus_gateway' | 'http_push';
  status: CatalogueStatus;
  billingGrade: boolean;
  price: CataloguePrice | null;
  gateway: { required: boolean; note: string };
  recurringCost: string;
  availability: 'in_stock' | 'on_order' | 'unknown';
  docsUrl: string | null;
  defaultMultiplier: number;
  multiplierNote: string;
  defaultChannel: string;
  channels: { value: string; label: string }[];
  setupSteps: string[];
  caveats: string[];
}

